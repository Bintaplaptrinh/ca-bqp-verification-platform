from __future__ import annotations

import argparse
import csv
import resource
import time
from pathlib import Path

from PIL import Image

from cabqp.modules.document_intelligence.ocr import get_engine
from cabqp.modules.document_intelligence.quality import VI_DIACRITICS
from cabqp.shared.settings import get_settings

from .common import error_rate, write_report


def _records(path: Path) -> dict[str, str]:
    with path.open(encoding='utf-8-sig', newline='') as f:
        return {r['record_id']: r['raw_text'] for r in csv.DictReader(f)}


def _manifest(path: Path) -> list[dict]:
    with path.open(encoding='utf-8-sig', newline='') as f:
        return [r for r in csv.DictReader(f) if r.get('document_type') == 'png_scan']


def _diacritic_accuracy(ref: str, hyp: str) -> float:
    r = [c for c in ref if c in VI_DIACRITICS]
    h = [c for c in hyp if c in VI_DIACRITICS]
    return max(0.0, 1.0 - error_rate(r, h))


def run(args) -> dict:
    truth = _records(Path(args.records))
    fixtures = _manifest(Path(args.manifest))
    configs = [('paddle', 'paddle'), ('paddle', 'vietocr'), ('tesseract', 'tesseract')]
    rows = []
    for detector, recognizer in configs:
        engine = get_engine(detector, recognizer)
        cer = wer = dia = latency = 0.0
        n = 0
        for item in fixtures:
            ref = truth.get(item['record_id'])
            if ref is None:
                continue
            image = Image.open(Path(args.root) / item['path']).convert('RGB')
            start = time.perf_counter()
            lines = engine.run(image)
            latency += time.perf_counter() - start
            hyp = '\n'.join(x.text for x in lines)
            cer += error_rate(list(ref), list(hyp))
            wer += error_rate(ref.split(), hyp.split())
            dia += _diacritic_accuracy(ref, hyp)
            n += 1
        rows.append({
            'engine': engine.name,
            'samples': n,
            'cer': cer / max(1, n),
            'wer': wer / max(1, n),
            'diacritic_accuracy': dia / max(1, n),
            'latency_seconds_per_page': latency / max(1, n),
            'max_rss_kb': resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,
        })
    return {
        'benchmark': 'ocr_accuracy',
        'threshold_version': get_settings().threshold_version,
        'fixture_manifest': str(args.manifest),
        'results': rows,
        'selection_rule': 'Prefer diacritic accuracy; switch recognizer only if materially better with acceptable latency/RAM.',
    }


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--records', required=True, help='Synthetic records CSV containing record_id,raw_text')
    p.add_argument('--manifest', required=True, help='document_manifest.csv generated by synthetic_data.documents')
    p.add_argument('--root', required=True, help='Root directory containing manifest paths')
    p.add_argument('--out-dir', default='docs/architecture')
    args = p.parse_args()
    payload = run(args)
    path = write_report('ocr_benchmark', payload, args.out_dir)
    print(path)


if __name__ == '__main__':
    main()
